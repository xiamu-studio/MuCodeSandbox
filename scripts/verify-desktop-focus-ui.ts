 await expect.poll(()=>service.manager.active.has(environment.id)).toBe(false);
 await expect(panel.getByRole('button',{name:'刷新状态',exact:true})).toBeEnabled({timeout:15000});
 await panel.getByRole('button',{name:'刷新状态',exact:true}).click();
