let claudeRunning=false,revealStatus=false,releaseStart:()=>void=()=>{};
const startBarrier=new Promise<void>(resolve=>{releaseStart=resolve;});
const status=(stale=false):DesktopAppsStatus=>({supported:true,displaySharedWithBrowser:true,accountTested:false,apps:(['grok-bot','claude-desktop'] as const).map(id=>({id,installed:true,installedVersion:'fixture',running:id==='grok-bot'||claudeRunning&&!stale,pid:100,profile:'fixture',rendererProtected:true}))});
service.manager.desktop.status=async()=>status();
service.manager.desktop.start=async()=>{await startBarrier;claudeRunning=true;};
service.manager.browser.ensureDisplay=async()=>{};
const directFocus:DesktopAppId[]=[],automaticFocus:string[]=[];
service.manager.browser.focus=async(_e,target)=>{directFocus.push(target as DesktopAppId);return true;};
service.guestBrowser.info=()=>({running:true,ready:true,browserRunning:false,width:3200,height:2000,platform:'Linux',display:undefined});
