import { chromium } from '@playwright/test';
import { mkdtemp, mkdir, rm, writeFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createService } from '../dist-server/server/service.js';

const root = path.resolve(import.meta.dirname, '..');
const temporary = await mkdtemp(path.join(homedir(), '.mu-ui-'));
const project = path.join(temporary, 'project'); await mkdir(project);
const results = path.join(root, 'test-results'); await mkdir(results, { recursive: true });
const service = await createService({ rootDir: root, dataDir: path.join(temporary, 'data'), port: 0 });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
const errors = [];
const responseErrors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error' && !message.text().startsWith('Failed to load resource:')) errors.push(message.text()); });
page.on('response', response => { if (response.status() >= 400 && response.url().includes('/api/')) responseErrors.push({ url: response.url(), status: response.status() }); });
try {
  await page.goto(service.launchUrl());
  await page.getByRole('heading', { name: 'MuCodeSandbox', exact: true }).waitFor();
  await page.getByRole('button', { name: '新建环境', exact: true }).first().click();
  await page.getByRole('textbox', { name: '环境名称', exact: true }).fill('MuCodeSandbox 开发环境');
  await page.getByRole('textbox', { name: '备注', exact: true }).fill('本地项目 · 只读共享');
  await page.getByRole('spinbutton', { name: '磁盘容量 / GiB', exact: true }).fill('9');
  await page.getByRole('button', { name: '创建环境', exact: true }).click();
  assert.equal(service.manager.store.list().length, 0, 'invalid disk capacity must not create an environment');
  await page.getByRole('spinbutton', { name: '磁盘容量 / GiB', exact: true }).fill('20');
  await page.getByRole('button', { name: '添加项目目录' }).click();
  await page.getByRole('textbox', { name: '本机项目目录', exact: true }).fill(project);
  await page.getByRole('button', { name: '创建环境', exact: true }).click();
  await page.getByRole('heading', { name: 'MuCodeSandbox 开发环境', exact: true }).waitFor();
  assert.equal(service.manager.store.list().length, 1, 'adding a directory must not submit the create form');
  assert.equal(service.manager.store.list()[0].diskGiB, 20, 'chosen disk capacity must reach the stored configuration');
  await page.screenshot({ path: path.join(results, 'desktop-overview.png'), fullPage: true });
  await page.getByRole('button', { name: '网络', exact: true }).click();
  await page.getByRole('button', { name: 'HTTP 代理', exact: true }).click();
  await page.getByRole('textbox', { name: '代理服务器' }).fill('127.0.0.1');
  await page.getByRole('spinbutton', { name: '端口', exact: true }).fill('7890');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.getByText('网络配置已保存', { exact: true }).waitFor();
  await page.getByRole('checkbox', { name: '仅代理联网（Linux 防火墙）' }).check();
  await page.getByRole('button', { name: '透明代理', exact: true }).click();
  await page.getByRole('textbox', { name: 'DNS 服务地址', exact: true }).fill('9.9.9.9');
  await page.getByRole('textbox', { name: 'TLS 服务名称', exact: true }).fill('dns.quad9.net');
  await page.getByRole('spinbutton', { name: 'DNS 端口', exact: true }).fill('8443');
  await page.getByRole('textbox', { name: 'DNS 请求路径', exact: true }).fill('/custom/dns-query');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.getByText('网络配置已保存', { exact: true }).waitFor();
  assert.equal(service.manager.store.list()[0].network.strict, true);
  assert.equal(service.manager.store.list()[0].network.transparent, true);
  assert.deepEqual(service.manager.store.list()[0].network.dns, { address: '9.9.9.9', serverName: 'dns.quad9.net', port: 8443, path: '/custom/dns-query' });
  await page.getByRole('button', { name: '检测防护', exact: true }).click();
  await page.getByText('未生效 / 环境已停止', { exact: true }).waitFor();
  await page.screenshot({ path: path.join(results, 'desktop-network.png'), fullPage: true });
  await page.getByRole('button', { name: '项目目录', exact: true }).click();
  assert.equal(await page.getByRole('checkbox', { name: '允许修改本机文件' }).isChecked(), false);
  await page.getByRole('button', { name: '设置', exact: true }).click();
  await page.getByRole('combobox', { name: '时区', exact: true }).fill('America/New_York');
  await page.getByRole('combobox', { name: '语言', exact: true }).selectOption('en-US');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.getByText('环境设置已保存', { exact: true }).waitFor();
  assert.equal(service.manager.store.list()[0].identity.timezone, 'America/New_York');
  assert.equal(service.manager.store.list()[0].network.strict, true, 'saving identity must preserve network enforcement');
  assert.equal(service.manager.store.list()[0].network.transparent, true, 'saving identity must preserve transparent mode');
  assert.equal(service.manager.store.list()[0].network.dns.port, 8443, 'saving identity must preserve DNS settings');
  await page.screenshot({ path: path.join(results, 'desktop-identity.png'), fullPage: true });
  await page.getByRole('button', { name: '总览', exact: true }).click();
  await page.getByRole('button', { name: '启动', exact: true }).click();
  await page.getByText('请先安装 Lima 运行组件', { exact: true }).waitFor();
  await page.getByRole('button', { name: '关闭提示' }).click();
  await page.getByRole('button', { name: '工作区', exact: true }).click();
  await page.screenshot({ path: path.join(results, 'desktop-workspace.png'), fullPage: true });
  await page.getByRole('button', { name: '检测实验室', exact: true }).click();
  await page.getByText('本机对照与原始接收端', { exact: true }).click();
  await page.getByRole('button', { name: '启动', exact: true }).click();
  await page.getByRole('button', { name: '停止', exact: true }).waitFor();
  await page.screenshot({ path: path.join(results, 'desktop-lab.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(results, 'mobile-lab.png'), fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'mobile lab must fit');
  await page.getByRole('button', { name: '停止', exact: true }).click();
  await page.getByRole('button', { name: '工作区', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(results, 'mobile-workspace.png'), fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'mobile workspace must fit');
  await page.getByRole('button', { name: /MuCodeSandbox 开发环境.*Linux 沙箱/ }).click();
  await page.screenshot({ path: path.join(results, 'mobile-overview.png'), fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'mobile environment must fit');
  await page.getByRole('button', { name: '网络', exact: true }).click();
  assert.equal(await page.getByRole('spinbutton', { name: 'DNS 端口', exact: true }).inputValue(), '8443');
  assert.equal(await page.getByRole('textbox', { name: 'DNS 请求路径', exact: true }).inputValue(), '/custom/dns-query');
  await page.screenshot({ path: path.join(results, 'mobile-network.png'), fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'mobile network controls must fit');
  await page.getByRole('button', { name: '设置', exact: true }).click();
  await page.screenshot({ path: path.join(results, 'mobile-identity.png'), fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'mobile identity controls must fit');
  await page.getByRole('button', { name: '新建环境', exact: true }).click();
  await page.getByRole('dialog').getByRole('textbox', { name: '环境名称', exact: true }).fill('这是一个用于检查移动端长名称布局的环境名称');
  await page.screenshot({ path: path.join(results, 'mobile-create.png'), fullPage: true });
  const modal = await page.getByRole('dialog').boundingBox();
  assert.ok(modal && modal.x >= 0 && modal.x + modal.width <= 390, 'mobile dialog must fit');
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await page.setViewportSize({ width: 1440, height: 960 });
  await page.getByRole('button', { name: '设置', exact: true }).click();
  await page.getByRole('button', { name: '删除环境', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: '删除环境', exact: true }).click();
  await page.getByText('还没有环境', { exact: true }).waitFor();
  assert.deepEqual(errors, []);
  assert.ok(responseErrors.every(r => r.status === 409 && r.url.endsWith('/actions/start')), 'only the tested runtime-missing request may fail');
  const report = { passed: true, viewports: ['1440x960', '390x844'], workflows: ['create environment with selected disk capacity and read-only mount', 'reject disk capacity below minimum', 'save and reopen all four DNS settings', 'save proxy and strict policy', 'inspect stopped protection', 'save identity and preserve strict policy and DNS', 'runtime missing state', 'lab start and stop', 'mobile network, lab and identity layout', 'delete environment'], browserErrors: errors, responseErrors };
  await writeFile(path.join(results, 'ui-verification.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
} finally { await browser.close(); await service.close(); await rm(temporary, { recursive: true, force: true }); }
